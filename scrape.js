#!/usr/bin/env node
'use strict';

/**
 * Vavoo M3U8 Scraper — Portugal playlist + public XMLTV EPG link
 */

const fs = require('fs');
const path = require('path');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const SEED_BASES = [
  'https://vavoo.to',
  'https://geil.to',
  'https://kool.to',
  'https://vavoo.net',
  'https://huhu.to',
  'https://oha.to'
];

/** Public Portugal XMLTV (uncompressed — works in more players than .gz) */
const EPG_URL_PT = 'https://xmltv.live/epg/pt.xml';

function parseArgs(argv) {
  const args = {
    resolve: false,
    base: null,
    out: path.join('output', 'playlist-portugal.m3u'),
    country: 'Portugal'
  };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--resolve') args.resolve = true;
    else if (a === '--base') args.base = argv[++i];
    else if (a === '--out') args.out = argv[++i];
    else if (a === '--country') args.country = argv[++i];
  }
  return args;
}

async function fetchJson(url) {
  const res = await fetch(url, {
    headers: { 'User-Agent': UA, Accept: 'application/json' }
  });
  if (!res.ok) {
    const body = await res.text().catch(() => '');
    throw new Error(`HTTP ${res.status} ${url}: ${body.slice(0, 120)}`);
  }
  return res.json();
}

async function pickBase(forced) {
  if (forced) return forced.replace(/\/$/, '');
  for (const b of SEED_BASES) {
    try {
      const url =
        b +
        '/live/catalog/live/channels.json?language=en&sort=name&filter%5Bgroup%5D=Portugal';
      const res = await fetch(url, {
        headers: { 'User-Agent': UA, Accept: 'application/json' }
      });
      if (!res.ok) continue;
      const data = await res.json();
      if (Array.isArray(data.items)) {
        console.log('[base]', b);
        return b;
      }
    } catch (_) {
      /* try next */
    }
  }
  throw new Error('No working Vavoo/Geil mirror found');
}

async function fetchAllChannels(base, country) {
  const items = [];
  let cursor = null;
  let guard = 0;
  do {
    const qs = new URLSearchParams({
      language: 'en',
      sort: 'name',
      'filter[group]': country
    });
    if (cursor) qs.set('cursor', cursor);
    const url = `${base}/live/catalog/live/channels.json?${qs}`;
    const data = await fetchJson(url);
    const page = Array.isArray(data.items) ? data.items : [];
    items.push(...page);
    cursor = data.nextCursor || null;
    guard += 1;
    console.log(`[catalog] page ${guard}: +${page.length} (total ${items.length})`);
  } while (cursor && guard < 30);
  return items;
}

function logoUrl(base, raw) {
  const fromApi = raw.images?.logo || raw.images?.poster || raw.logo;
  if (fromApi) {
    if (/^https?:\/\//i.test(fromApi)) return fromApi;
    return base + (fromApi.startsWith('/') ? fromApi : '/' + fromApi);
  }
  if (raw.id) return `${base}/live2/logo/${raw.id}.png`;
  return '';
}

function playUrl(base, raw) {
  if (raw.url && /^https?:\/\//i.test(raw.url)) return raw.url;
  return `${base}/live/play/${raw.id}`;
}

async function resolveStream(base, play) {
  const url = `${base}/live/resolve?url=${encodeURIComponent(play)}`;
  const data = await fetchJson(url);
  if (!data?.url) throw new Error('no url in resolve response');
  return data.url;
}

function m3uEscape(s) {
  return String(s || '').replace(/\r?\n/g, ' ').trim();
}

function buildM3u(channels, { epgUrl, groupTitle }) {
  const lines = [
    `#EXTM3U url-tvg="${epgUrl}"`,
    `# Generated by vavoo-m3u8-scraper — ${new Date().toISOString()}`
  ];

  for (const ch of channels) {
    const name = m3uEscape(ch.name);
    const logo = m3uEscape(ch.logo || '');
    const tvgId = m3uEscape(ch.tvgId || '');
    const attrs = [
      tvgId ? `tvg-id="${tvgId}"` : null,
      logo ? `tvg-logo="${logo}"` : null,
      `group-title="${m3uEscape(groupTitle)}"`
    ]
      .filter(Boolean)
      .join(' ');

    lines.push(`#EXTINF:-1 ${attrs},${name}`);
    lines.push(ch.streamUrl);
  }
  return lines.join('\n') + '\n';
}

async function main() {
  const args = parseArgs(process.argv);
  const base = await pickBase(args.base);
  const rawItems = await fetchAllChannels(base, args.country);
  console.log(`[catalog] ${rawItems.length} channels for ${args.country}`);

  const channels = [];
  let resolved = 0;
  let failed = 0;

  for (const raw of rawItems) {
    const play = playUrl(base, raw);
    let streamUrl = play;
    if (args.resolve) {
      try {
        streamUrl = await resolveStream(base, play);
        resolved += 1;
        process.stdout.write(`\r[resolve] ${resolved}/${rawItems.length}`);
      } catch (err) {
        failed += 1;
        console.warn(`\n[resolve] fail ${raw.name}: ${err.message}`);
        continue; // skip channels that cannot resolve
      }
    }

    channels.push({
      id: String(raw.id),
      name: raw.name || `Channel ${raw.id}`,
      tvgId: raw.ids?.tvg || '',
      logo: logoUrl(base, raw),
      streamUrl
    });
  }
  if (args.resolve) console.log(`\n[resolve] ok=${resolved} fail=${failed}`);

  // Prefer unique names order as returned; optional light de-dupe by name+url
  const outPath = path.resolve(args.out);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });

  const epgUrl = args.country.toLowerCase() === 'portugal' ? EPG_URL_PT : EPG_URL_PT;
  const body = buildM3u(channels, {
    epgUrl,
    groupTitle: args.country
  });
  fs.writeFileSync(outPath, body, 'utf8');

  console.log(`[done] ${channels.length} entries → ${outPath}`);
  console.log(`[epg]  ${epgUrl}`);
  if (!args.resolve) {
    console.log(
      '[hint] Playlist uses /live/play/ links. For real HLS URLs run: node scrape.js --resolve'
    );
  } else {
    console.log('[hint] Resolved HLS URLs expire; re-run --resolve when streams die.');
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
